from __future__ import annotations
from typing import Dict, List, Set, Tuple


class Grammar:
    """
    Context‑Free Grammar in Chomsky Normal Form (CNF).

    Attributes
    ----------
    start : str
        The start non‑terminal symbol.
    productions : Dict[str, List[Tuple[str, ...]]]
        Mapping from a left‑hand side non‑terminal to a list of right‑hand side tuples.
        Each tuple is either:
            * (terminal,)                – a terminal production
            * (nonterm1, nonterm2)       – a binary non‑terminal production
            * ()                         – an epsilon production (allowed only for the start symbol)
    """

    def __init__(self, start: str) -> None:
        self.start: str = start
        self.productions: Dict[str, List[Tuple[str, ...]]] = {}

    def add_production(self, lhs: str, rhs: Tuple[str, ...]) -> None:
        """Add a production lhs → rhs to the grammar."""
        if lhs not in self.productions:
            self.productions[lhs] = []
        self.productions[lhs].append(rhs)

    @classmethod
    def from_rules(cls, start: str, rules: List[Tuple[str, Tuple[str, ...]]]) -> Grammar:
        """
        Construct a Grammar from a list of rules.

        Parameters
        ----------
        start : str
            Start symbol.
        rules : List[Tuple[str, Tuple[str, ...]]]
            Each rule is a pair (lhs, rhs) where rhs is a tuple of symbols.
        """
        g = cls(start)
        for lhs, rhs in rules:
            g.add_production(lhs, rhs)
        return g


def cyk(grammar: Grammar, tokens: List[str]) -> bool:
    """
    CYK membership test for a string of tokens.

    Parameters
    ----------
    grammar : Grammar
        Grammar in CNF.
    tokens : List[str]
        Input string as a list of terminal symbols.

    Returns
    -------
    bool
        True iff the token sequence can be generated by the grammar.
    """
    n = len(tokens)

    # Empty string case – only possible via an epsilon production of the start symbol.
    if n == 0:
        for lhs, rhss in grammar.productions.items():
            if () in rhss and lhs == grammar.start:
                return True
        return False

    # table[i][j] holds the set of non‑terminals that derive the substring tokens[i..j] (inclusive).
    table: List[List[Set[str]]] = [[set() for _ in range(n)] for _ in range(n)]

    # Length‑1 substrings (terminals)
    for i, token in enumerate(tokens):
        for lhs, rhss in grammar.productions.items():
            for rhs in rhss:
                if len(rhs) == 1 and rhs[0] == token:
                    table[i][i].add(lhs)

    # Substrings of length >= 2
    for span in range(2, n + 1):          # span length
        for i in range(n - span + 1):     # start index
            j = i + span - 1              # end index
            for k in range(i, j):         # split point
                left = table[i][k]
                right = table[k + 1][j]
                if not left or not right:
                    continue
                # For each production A → B C, check if B ∈ left and C ∈ right.
                for lhs, rhss in grammar.productions.items():
                    for rhs in rhss:
                        if len(rhs) == 2:
                            B, C = rhs
                            if B in left and C in right:
                                table[i][j].add(lhs)

    return grammar.start in table[0][n - 1]
