from __future__ import annotations
from typing import Dict, List, Set, Tuple


class Grammar:
    """
    Context‑Free Grammar in Chomsky Normal Form.

    Attributes
    ----------
    start : str
        The start non‑terminal.
    productions : Dict[str, List[Tuple[str, ...]]]
        Mapping from a non‑terminal to a list of right‑hand sides.
        Each right‑hand side is a tuple of length 1 (terminal) or 2 (non‑terminals).
    """

    def __init__(self, start: str) -> None:
        self.start: str = start
        self.productions: Dict[str, List[Tuple[str, ...]]] = {}

    def add_production(self, left: str, right: Tuple[str, ...]) -> None:
        """Add a production `left -> right`."""
        if len(right) not in (1, 2):
            raise ValueError("CNF productions must have 1 or 2 symbols on the right‑hand side.")
        self.productions.setdefault(left, []).append(right)

    def terminals_map(self) -> Dict[str, Set[str]]:
        """
        Build a map from terminal symbols to the set of non‑terminals that produce them.
        Returns
        -------
        Dict[str, Set[str]]
        """
        term_map: Dict[str, Set[str]] = {}
        for left, rhss in self.productions.items():
            for rhs in rhss:
                if len(rhs) == 1 and not rhs[0].isupper():
                    term_map.setdefault(rhs[0], set()).add(left)
        return term_map

    def binary_map(self) -> Dict[Tuple[str, str], Set[str]]:
        """
        Build a map from a pair of non‑terminals (B, C) to the set of A such that A -> B C.
        Returns
        -------
        Dict[Tuple[str, str], Set[str]]
        """
        bin_map: Dict[Tuple[str, str], Set[str]] = {}
        for left, rhss in self.productions.items():
            for rhs in rhss:
                if len(rhs) == 2:
                    bin_map.setdefault((rhs[0], rhs[1]), set()).add(left)
        return bin_map


def cyk_parse(grammar: Grammar, tokens: List[str]) -> bool:
    """
    CYK membership test for a string of terminals.

    Parameters
    ----------
    grammar : Grammar
        A CNF grammar.
    tokens : List[str]
        The input string as a list of terminal symbols.

    Returns
    -------
    bool
        True iff the token list is generated by the grammar.
    """
    n = len(tokens)
    if n == 0:
        # CNF without epsilon productions cannot generate the empty string.
        return False

    # Pre‑compute helper maps for O(1) look‑ups.
    term_map = grammar.terminals_map()
    bin_map = grammar.binary_map()

    # table[i][j] holds the set of non‑terminals that derive tokens[i..j] (inclusive).
    table: List[List[Set[str]]] = [[set() for _ in range(n)] for _ in range(n)]

    # Fill the diagonal (substrings of length 1).
    for i, token in enumerate(tokens):
        table[i][i] = term_map.get(token, set()).copy()

    # Fill upper triangle for substrings of length >= 2.
    for length in range(2, n + 1):          # length of the span
        for i in range(n - length + 1):    # start index
            j = i + length - 1             # end index
            cell: Set[str] = set()
            for k in range(i, j):          # split point
                left_set = table[i][k]
                right_set = table[k + 1][j]
                for B in left_set:
                    for C in right_set:
                        producers = bin_map.get((B, C))
                        if producers:
                            cell.update(producers)
            table[i][j] = cell

    # The string is in the language iff the start symbol derives the whole string.
    return grammar.start in table[0][n - 1]


__all__ = ["Grammar", "cyk_parse"]
