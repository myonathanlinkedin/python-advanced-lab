from __future__ import annotations

from typing import List, Set

from custom_types import Grammar, Production, Symbol


def cyk(grammar: Grammar, tokens: List[Symbol]) -> bool:
    """
    CYK membership test for a string of tokens.

    Parameters
    ----------
    grammar : Grammar
        A CNF grammar.
    tokens : list of Symbol
        The input string as a list of terminal symbols.

    Returns
    -------
    bool
        True iff the string can be generated by ``grammar.start``.
    """
    n = len(tokens)

    # Handle the empty string explicitly.
    if n == 0:
        # In CNF only the start symbol may derive ε.
        return any(p.lhs == grammar.start and len(p.rhs) == 0 for p in grammar.productions)

    # table[i][j] holds the set of non‑terminals that derive the substring tokens[i..j] (inclusive).
    table: List[List[Set[Symbol]]] = [[set() for _ in range(n)] for _ in range(n)]

    # Length‑1 substrings (the diagonal).
    for i, token in enumerate(tokens):
        for prod in grammar.productions:
            if len(prod.rhs) == 1 and prod.rhs[0] == token:
                table[i][i].add(prod.lhs)

    # Substrings of length >= 2.
    for span in range(2, n + 1):          # span = length of the substring
        for i in range(n - span + 1):    # start index
            j = i + span - 1             # end index
            for k in range(i, j):        # split point
                left = table[i][k]
                right = table[k + 1][j]
                if not left or not right:
                    continue
                # For each binary production A → B C, check if B ∈ left and C ∈ right.
                for prod in grammar.productions:
                    if len(prod.rhs) == 2:
                        B, C = prod.rhs
                        if B in left and C in right:
                            table[i][j].add(prod.lhs)

    # Acceptance condition: start symbol must generate the whole string.
    return grammar.start in table[0][n - 1]
